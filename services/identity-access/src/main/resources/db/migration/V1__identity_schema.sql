CREATE TABLE tenants (
    id UUID PRIMARY KEY,
    name TEXT NOT NULL CHECK (length(name) BETWEEN 1 AND 200),
    status TEXT NOT NULL CHECK (status IN ('ACTIVE', 'SUSPENDED', 'ARCHIVED')),
    version BIGINT NOT NULL DEFAULT 1 CHECK (version > 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_by TEXT NOT NULL,
    updated_by TEXT NOT NULL
);

COMMENT ON COLUMN tenants.id IS 'Stable tenant identifier generated by Identity Access.';
COMMENT ON COLUMN tenants.name IS 'Tenant display name.';
COMMENT ON COLUMN tenants.status IS 'Tenant lifecycle state.';
COMMENT ON COLUMN tenants.version IS 'Optimistic concurrency version.';
COMMENT ON COLUMN tenants.created_at IS 'Creation timestamp in UTC.';
COMMENT ON COLUMN tenants.updated_at IS 'Last mutation timestamp in UTC.';
COMMENT ON COLUMN tenants.created_by IS 'Opaque actor reference that created the tenant.';
COMMENT ON COLUMN tenants.updated_by IS 'Opaque actor reference that last changed the tenant.';

CREATE TABLE branches (
    id UUID PRIMARY KEY,
    tenant_id UUID NOT NULL REFERENCES tenants(id),
    code TEXT NOT NULL,
    normalized_code TEXT NOT NULL,
    name TEXT NOT NULL CHECK (length(name) BETWEEN 1 AND 200),
    address TEXT CHECK (address IS NULL OR length(address) <= 500),
    status TEXT NOT NULL CHECK (status IN ('ACTIVE', 'ARCHIVED')),
    version BIGINT NOT NULL DEFAULT 1 CHECK (version > 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_by TEXT NOT NULL,
    updated_by TEXT NOT NULL,
    CONSTRAINT uq_branches_tenant_id UNIQUE (tenant_id, id),
    CONSTRAINT uq_branches_tenant_code UNIQUE (tenant_id, normalized_code)
);

COMMENT ON COLUMN branches.id IS 'Stable branch identifier generated by Identity Access.';
COMMENT ON COLUMN branches.tenant_id IS 'Tenant that owns the branch.';
COMMENT ON COLUMN branches.code IS 'Human-facing branch code.';
COMMENT ON COLUMN branches.normalized_code IS 'Normalized branch code used for uniqueness.';
COMMENT ON COLUMN branches.name IS 'Branch display name.';
COMMENT ON COLUMN branches.address IS 'Optional branch display address.';
COMMENT ON COLUMN branches.status IS 'Branch lifecycle state.';
COMMENT ON COLUMN branches.version IS 'Optimistic concurrency version.';
COMMENT ON COLUMN branches.created_at IS 'Creation timestamp in UTC.';
COMMENT ON COLUMN branches.updated_at IS 'Last mutation timestamp in UTC.';
COMMENT ON COLUMN branches.created_by IS 'Opaque actor reference that created the branch.';
COMMENT ON COLUMN branches.updated_by IS 'Opaque actor reference that last changed the branch.';

CREATE INDEX idx_branches_tenant_status
    ON branches (tenant_id, status, id);

CREATE TABLE users (
    id UUID PRIMARY KEY,
    cognito_subject TEXT UNIQUE,
    normalized_email TEXT NOT NULL UNIQUE,
    display_name TEXT NOT NULL CHECK (length(display_name) BETWEEN 1 AND 200),
    phone TEXT,
    status TEXT NOT NULL CHECK (status IN ('ACTIVE', 'SUSPENDED', 'REVOKED')),
    reconciliation_status TEXT NOT NULL,
    last_authenticated_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

COMMENT ON COLUMN users.id IS 'Internal user identifier.';
COMMENT ON COLUMN users.cognito_subject IS 'Stable Cognito sub; null until activation/reconciliation.';
COMMENT ON COLUMN users.normalized_email IS 'Lowercase and trimmed invitation lookup email.';
COMMENT ON COLUMN users.display_name IS 'Minimal employee display name.';
COMMENT ON COLUMN users.phone IS 'Optional protected employee phone.';
COMMENT ON COLUMN users.status IS 'User profile lifecycle state.';
COMMENT ON COLUMN users.reconciliation_status IS 'Cognito mapping state such as PENDING or ALIGNED.';
COMMENT ON COLUMN users.last_authenticated_at IS 'Last observed successful authenticated request.';
COMMENT ON COLUMN users.created_at IS 'Local profile creation timestamp in UTC.';
COMMENT ON COLUMN users.updated_at IS 'Last profile or mapping mutation timestamp in UTC.';
